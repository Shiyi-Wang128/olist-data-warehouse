"""Profile the 9 raw Olist CSVs in data/raw/ (read-only) and write docs/data_profile.md.

Run: python src/explore/profile_raw.py
Re-running overwrites docs/data_profile.md (idempotent). It never touches data/raw/.
"""
import sys
import warnings
from pathlib import Path

import pandas as pd

warnings.filterwarnings("ignore")

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "data" / "raw"
OUT = ROOT / "docs" / "data_profile.md"

FILES = {
    "customers": "olist_customers_dataset.csv",
    "geolocation": "olist_geolocation_dataset.csv",
    "orders": "olist_orders_dataset.csv",
    "order_items": "olist_order_items_dataset.csv",
    "payments": "olist_order_payments_dataset.csv",
    "reviews": "olist_order_reviews_dataset.csv",
    "products": "olist_products_dataset.csv",
    "sellers": "olist_sellers_dataset.csv",
    "translation": "product_category_name_translation.csv",
}

# Primary-key candidates to test per table (each entry is a list of columns).
PK_CANDIDATES = {
    "customers": [["customer_id"], ["customer_unique_id"]],
    "geolocation": [["geolocation_zip_code_prefix"],
                    ["geolocation_zip_code_prefix", "geolocation_lat", "geolocation_lng"]],
    "orders": [["order_id"]],
    "order_items": [["order_id", "order_item_id"]],
    "payments": [["order_id", "payment_sequential"]],
    "reviews": [["review_id"], ["review_id", "order_id"]],
    "products": [["product_id"]],
    "sellers": [["seller_id"]],
    "translation": [["product_category_name"]],
}

TIME_COLS = {
    "orders": ["order_purchase_timestamp", "order_approved_at", "order_delivered_carrier_date",
               "order_delivered_customer_date", "order_estimated_delivery_date"],
    "order_items": ["shipping_limit_date"],
    "reviews": ["review_creation_date", "review_answer_timestamp"],
}

lines = []


def emit(text=""):
    lines.append(text)


def md_table(rows, header):
    emit("| " + " | ".join(header) + " |")
    emit("|" + "|".join(["---"] * len(header)) + "|")
    for r in rows:
        emit("| " + " | ".join(str(c) for c in r) + " |")
    emit()


def n(x):
    return f"{int(x):,}"


def pct(part, whole):
    return f"{part / whole * 100:.2f}%" if whole else "n/a"


def issue(name, count, base, note=""):
    """One issue row: name, affected rows, share of base, note."""
    return [name, n(count), pct(count, base), note]


def main():
    dfs = {k: pd.read_csv(RAW / v) for k, v in FILES.items()}
    ts_bad = {}
    for t, cols in TIME_COLS.items():
        for c in cols:
            raw_nonnull = dfs[t][c].notna()
            parsed = pd.to_datetime(dfs[t][c], errors="coerce")
            ts_bad[(t, c)] = int((raw_nonnull & parsed.isna()).sum())
            dfs[t][c] = parsed

    c, g, o, oi, p, r, pr, s, tr = (dfs[k] for k in
        ["customers", "geolocation", "orders", "order_items", "payments",
         "reviews", "products", "sellers", "translation"])

    emit("# Olist raw data profile")
    emit()
    emit("Generated by `src/explore/profile_raw.py` from `data/raw/` (read-only). "
         "Counts are real measurements; percentages are of the stated base table.")
    emit()

    # ---------------- Section 1: table overview ----------------
    emit("## 1. Row counts")
    emit()
    md_table([[k, n(len(d)), len(d.columns)] for k, d in dfs.items()], ["table", "rows", "columns"])

    # ---------------- Section 2: per-table detail ----------------
    emit("## 2. Per-table profile")
    emit()
    for k, d in dfs.items():
        emit(f"### {k} ({n(len(d))} rows)")
        emit()
        nulls = d.isna().sum()
        md_table([[col, str(d[col].dtype), n(nulls[col]), pct(nulls[col], len(d)), n(d[col].nunique())]
                  for col in d.columns],
                 ["column", "dtype", "nulls", "null %", "distinct"])
        pk_rows = []
        for cols in PK_CANDIDATES[k]:
            dup_rows = int(d.duplicated(subset=cols, keep=False).sum())
            extra = int(d.duplicated(subset=cols, keep="first").sum())
            pk_rows.append([", ".join(cols), "YES" if extra == 0 else "NO",
                            n(d[cols].drop_duplicates().shape[0]), n(extra), n(dup_rows)])
        emit("Primary-key candidates:")
        emit()
        md_table(pk_rows, ["columns", "unique?", "distinct keys", "extra rows (beyond first)",
                           "rows involved in dupes"])

    # ---------------- Section 3: data issues ----------------
    emit("## 3. Data issues")
    emit()

    # 3.1 customer_id vs customer_unique_id
    emit("### 3.1 customer_id vs customer_unique_id")
    emit()
    oc = o.merge(c[["customer_id", "customer_unique_id"]], on="customer_id", how="left")
    orders_per_person = oc.groupby("customer_unique_id")["order_id"].nunique()
    persons_multi = int((orders_per_person > 1).sum())
    md_table([
        ["distinct customer_id (customers table)", n(c["customer_id"].nunique())],
        ["distinct customer_unique_id (persons)", n(c["customer_unique_id"].nunique())],
        ["customer_id rows that share a unique_id with another", n(c["customer_unique_id"].duplicated(keep=False).sum())],
        ["persons with orders (via orders)", n(len(orders_per_person))],
        ["persons with >1 order", f"{n(persons_multi)} ({pct(persons_multi, len(orders_per_person))} of persons with orders)"],
        ["max orders by one person", n(orders_per_person.max())],
        ["orders whose customer_id has no match in customers", n(oc["customer_unique_id"].isna().sum())],
    ], ["metric", "value"])

    # 3.2 orders status / timestamps
    emit("### 3.2 Orders: status and timestamps")
    emit()
    emit("Order status distribution:")
    emit()
    vc = o["order_status"].value_counts()
    md_table([[st, n(v), pct(v, len(o))] for st, v in vc.items()], ["order_status", "orders", "%"])

    deliv = o["order_status"] == "delivered"
    ts_cols = TIME_COLS["orders"]
    emit("Missing timestamps per status (count of NULLs):")
    emit()
    rows = []
    for st in vc.index:
        sub = o[o["order_status"] == st]
        rows.append([st, n(len(sub))] + [n(sub[col].isna().sum()) for col in ts_cols])
    md_table(rows, ["status", "orders"] + ts_cols)

    def viol(a, b):
        both = o[a].notna() & o[b].notna()
        return int((both & (o[a] > o[b])).sum())

    order_checks = [
        ("status='delivered' but order_delivered_customer_date NULL",
         int((deliv & o["order_delivered_customer_date"].isna()).sum()), len(o), ""),
        ("status='delivered' but order_delivered_carrier_date NULL",
         int((deliv & o["order_delivered_carrier_date"].isna()).sum()), len(o), ""),
        ("status='delivered' but order_approved_at NULL",
         int((deliv & o["order_approved_at"].isna()).sum()), len(o), ""),
        ("status!='delivered' but order_delivered_customer_date NOT NULL",
         int((~deliv & o["order_delivered_customer_date"].notna()).sum()), len(o), ""),
        ("approved_at < purchase_timestamp", viol("order_purchase_timestamp", "order_approved_at"), len(o), "approval before purchase"),
        ("delivered_carrier < approved_at", viol("order_approved_at", "order_delivered_carrier_date"), len(o), "handed to carrier before approval"),
        ("delivered_customer < delivered_carrier", viol("order_delivered_carrier_date", "order_delivered_customer_date"), len(o), "delivered before shipped"),
        ("delivered_customer < purchase_timestamp", viol("order_purchase_timestamp", "order_delivered_customer_date"), len(o), "delivered before purchase"),
        ("estimated_delivery < purchase_timestamp", viol("order_purchase_timestamp", "order_estimated_delivery_date"), len(o), ""),
    ]
    md_table([issue(a, b, base, note) for a, b, base, note in order_checks],
             ["check", "affected orders", "% of orders", "note"])
    emit("Unparseable timestamp strings (non-null but not a valid datetime):")
    emit()
    md_table([[f"{t}.{col}", n(v)] for (t, col), v in ts_bad.items()], ["column", "bad values"])
    emit(f"Purchase timestamp range: {o['order_purchase_timestamp'].min()} -> {o['order_purchase_timestamp'].max()}")
    emit()
    monthly = o.groupby(o["order_purchase_timestamp"].dt.to_period("M")).size()
    md_table([[str(m), n(v)] for m, v in monthly.items()], ["purchase month", "orders"])

    # 3.3 products / categories
    emit("### 3.3 Products and category translation")
    emit()
    cat_null = pr["product_category_name"].isna()
    known = set(tr["product_category_name"])
    cats = pr.loc[~cat_null, "product_category_name"]
    no_trans = cats[~cats.isin(known)]
    dim_cols = ["product_weight_g", "product_length_cm", "product_height_cm", "product_width_cm"]
    prod_checks = [
        issue("product_category_name NULL", cat_null.sum(), len(pr)),
        issue("category present but missing from translation table (products)", len(no_trans), len(pr),
              f"{no_trans.nunique()} distinct categories: {', '.join(sorted(no_trans.unique()))}"),
        issue("translation categories never used by any product", len(known - set(cats)), len(tr)),
        issue("any dimension/weight NULL", pr[dim_cols].isna().any(axis=1).sum(), len(pr)),
        issue("product_weight_g == 0", (pr["product_weight_g"] == 0).sum(), len(pr)),
        issue("any of length/height/width == 0", (pr[dim_cols[1:]] == 0).any(axis=1).sum(), len(pr)),
        issue("product_name_lenght / photos_qty NULL", pr["product_name_lenght"].isna().sum(), len(pr),
              "same rows as category NULL expected"),
    ]
    md_table([list(x) for x in prod_checks], ["check", "affected rows", "% of products", "note"])
    both_null = int((cat_null & pr["product_name_lenght"].isna()).sum())
    emit(f"Rows with category NULL and name-length NULL together: {n(both_null)}")
    emit()
    emit("Note: raw column names `product_name_lenght` / `product_description_lenght` are misspelled in the source.")
    emit()
    # order_items affected by missing category
    oi_p = oi.merge(pr[["product_id", "product_category_name"]], on="product_id", how="left")
    emit(f"order_items rows whose product has NULL category: "
         f"{n(oi_p['product_category_name'].isna().sum())} ({pct(oi_p['product_category_name'].isna().sum(), len(oi))}) "
         f"(includes product_id not found in products)")
    emit()

    # 3.4 reviews
    emit("### 3.4 Reviews")
    emit()
    dup_ids = r["review_id"].duplicated(keep=False)
    dup_id_groups = r.loc[dup_ids, "review_id"].nunique()
    same_id_diff_order = r.groupby("review_id")["order_id"].nunique()
    rev_checks = [
        issue("rows with a duplicated review_id", dup_ids.sum(), len(r)),
        issue("distinct review_ids that are duplicated", dup_id_groups, r["review_id"].nunique()),
        issue("extra rows beyond first per review_id", r["review_id"].duplicated().sum(), len(r)),
        issue("review_ids linked to >1 order_id", (same_id_diff_order > 1).sum(), r["review_id"].nunique()),
        issue("fully identical rows", r.duplicated().sum(), len(r)),
        issue("duplicated (review_id, order_id) pairs (extra rows)", r.duplicated(["review_id", "order_id"]).sum(), len(r)),
        issue("orders with >1 review", (r.groupby("order_id").size() > 1).sum(), r["order_id"].nunique()),
        issue("review_score outside 1..5 or NULL", (~r["review_score"].between(1, 5)).sum(), len(r)),
        issue("review_comment_title NULL", r["review_comment_title"].isna().sum(), len(r)),
        issue("review_comment_message NULL", r["review_comment_message"].isna().sum(), len(r)),
        issue("review_answer_timestamp < review_creation_date",
              (r["review_answer_timestamp"] < r["review_creation_date"]).sum(), len(r)),
    ]
    md_table([list(x) for x in rev_checks], ["check", "affected", "% of base", "note"])

    # 3.5 geolocation
    emit("### 3.5 Geolocation")
    emit()
    gz = "geolocation_zip_code_prefix"
    coords = g.groupby(gz).apply(lambda x: x[["geolocation_lat", "geolocation_lng"]].drop_duplicates().shape[0])
    outside = ~(g["geolocation_lat"].between(-34, 6) & g["geolocation_lng"].between(-74, -34))
    geo_zips = set(g[gz])
    geo_checks = [
        issue("fully duplicated rows (extra beyond first)", g.duplicated().sum(), len(g)),
        issue("rows involved in full duplication", g.duplicated(keep=False).sum(), len(g)),
        issue("distinct zip prefixes", g[gz].nunique(), g[gz].nunique(), "base rows would be 1 row per prefix"),
        issue("zip prefixes with >1 distinct (lat,lng)", (coords > 1).sum(), g[gz].nunique()),
        issue("rows with coordinates outside Brazil bounding box", outside.sum(), len(g),
              "lat -34..6, lng -74..-34"),
        issue("distinct city spellings", g["geolocation_city"].nunique(), g["geolocation_city"].nunique(),
              "same city appears with many spellings/accents"),
        issue("geolocation_state not a 2-letter uppercase code", (~g["geolocation_state"].astype(str).str.fullmatch(r"[A-Z]{2}")).sum(), len(g)),
        issue("customer zip prefixes not in geolocation (customers rows)", (~c["customer_zip_code_prefix"].isin(geo_zips)).sum(), len(c)),
        issue("seller zip prefixes not in geolocation (sellers rows)", (~s["seller_zip_code_prefix"].isin(geo_zips)).sum(), len(s)),
    ]
    md_table([list(x) for x in geo_checks], ["check", "affected", "% of base", "note"])
    emit("Note: zip prefixes are read as integers, so leading zeros (e.g. 01046) are lost; "
         "all tables share this, so joins still work, but DWD should store them as zero-padded 5-char strings.")
    emit()

    # 3.6 foreign keys
    emit("### 3.6 Foreign-key integrity")
    emit()

    def fk(child, col, parent_df, pcol, label):
        mask = ~child[col].isin(set(parent_df[pcol]))
        return [label, n(mask.sum()), pct(mask.sum(), len(child)),
                n(child.loc[mask, col].nunique())]

    fk_rows = [
        fk(oi, "order_id", o, "order_id", "order_items.order_id NOT IN orders"),
        fk(oi, "product_id", pr, "product_id", "order_items.product_id NOT IN products"),
        fk(oi, "seller_id", s, "seller_id", "order_items.seller_id NOT IN sellers"),
        fk(o, "customer_id", c, "customer_id", "orders.customer_id NOT IN customers"),
        fk(p, "order_id", o, "order_id", "payments.order_id NOT IN orders"),
        fk(r, "order_id", o, "order_id", "reviews.order_id NOT IN orders"),
    ]
    md_table(fk_rows, ["relationship", "orphan child rows", "% of child rows", "distinct orphan keys"])
    emit("Reverse direction (parents without children):")
    emit()
    items_orders = set(oi["order_id"])
    pay_orders = set(p["order_id"])
    rev_orders = set(r["order_id"])
    no_item = o[~o["order_id"].isin(items_orders)]
    rev_rows = [
        issue("orders with no order_items", len(no_item), len(o),
              "by status: " + ", ".join(f"{k}={v}" for k, v in no_item["order_status"].value_counts().items())),
        issue("orders with no payments", (~o["order_id"].isin(pay_orders)).sum(), len(o)),
        issue("orders with no reviews", (~o["order_id"].isin(rev_orders)).sum(), len(o)),
        issue("orders (delivered) with no order_items", (no_item["order_status"] == "delivered").sum(),
              int(deliv.sum())),
        issue("customers with no orders", (~c["customer_id"].isin(set(o["customer_id"]))).sum(), len(c)),
        issue("products never sold", (~pr["product_id"].isin(set(oi["product_id"]))).sum(), len(pr)),
        issue("sellers with no items", (~s["seller_id"].isin(set(oi["seller_id"]))).sum(), len(s)),
    ]
    md_table([list(x) for x in rev_rows], ["check", "affected", "% of base", "note"])

    # 3.7 other suspicious
    emit("### 3.7 Other suspicious findings")
    emit()
    # Compare in integer cents: float sums of 2-decimal values drift around the 0.01 boundary.
    item_tot = ((oi["price"] + oi["freight_value"]) * 100).round().astype("int64").groupby(oi["order_id"]).sum()
    pay_tot = (p["payment_value"] * 100).round().astype("int64").groupby(p["order_id"]).sum()
    cmp_ = pd.concat([item_tot.rename("items"), pay_tot.rename("pay")], axis=1).dropna()
    cents_diff = (cmp_["items"] - cmp_["pay"]).abs()
    mism = cents_diff >= 2
    items_base = oi.drop_duplicates(["order_id", "order_item_id"])
    oi_ts = oi["shipping_limit_date"]
    merged = oi.merge(o[["order_id", "order_purchase_timestamp"]], on="order_id", how="inner")
    sus = [
        issue("order_items price <= 0", (oi["price"] <= 0).sum(), len(oi)),
        issue("order_items freight_value < 0", (oi["freight_value"] < 0).sum(), len(oi)),
        issue("order_items freight_value == 0", (oi["freight_value"] == 0).sum(), len(oi), "may be legit free shipping"),
        issue("order_items price > 99.9th percentile", (oi["price"] > oi["price"].quantile(0.999)).sum(), len(oi),
              f"max price {oi['price'].max():.2f}, p99.9 {oi['price'].quantile(0.999):.2f}"),
        issue("shipping_limit_date < purchase_timestamp", (merged["shipping_limit_date"] < merged["order_purchase_timestamp"]).sum(),
              len(merged)),
        issue("order_items with order_item_id gaps (max id != item count per order)",
              int((oi.groupby("order_id")["order_item_id"].max() != oi.groupby("order_id").size()).sum()),
              oi["order_id"].nunique(), "base = orders with items"),
        issue("payments payment_value == 0", (p["payment_value"] == 0).sum(), len(p)),
        issue("payments payment_value < 0", (p["payment_value"] < 0).sum(), len(p)),
        issue("payments payment_type == 'not_defined'", (p["payment_type"] == "not_defined").sum(), len(p)),
        issue("payments payment_installments == 0", (p["payment_installments"] == 0).sum(), len(p)),
        issue("orders where sum(price+freight) differs from sum(payment_value) by >= 2 cents", mism.sum(), len(cmp_),
              "base = orders having both items and payments"),
        issue("same, differing by exactly 1 cent (rounding noise)", (cents_diff == 1).sum(), len(cmp_),
              "base = orders having both items and payments"),
        issue("customer_state not 2-letter uppercase", (~c["customer_state"].astype(str).str.fullmatch(r"[A-Z]{2}")).sum(), len(c)),
        issue("seller_state not 2-letter uppercase", (~s["seller_state"].astype(str).str.fullmatch(r"[A-Z]{2}")).sum(), len(s)),
        issue("customer_city containing non-ASCII chars", c["customer_city"].astype(str).map(lambda x: not x.isascii()).sum(), len(c)),
        issue("seller_city with digits/slash/@ (dirty text)", s["seller_city"].astype(str).str.contains(r"[\d/@\\]").sum(), len(s)),
        issue("seller_city not lowercase", (s["seller_city"].astype(str) != s["seller_city"].astype(str).str.lower()).sum(), len(s)),
        issue("sellers duplicated on all columns", s.duplicated().sum(), len(s)),
        issue("customers duplicated on all columns", c.duplicated().sum(), len(c)),
        issue("same customer_unique_id with different zip/state across customer_ids",
              int((c.groupby("customer_unique_id")[["customer_zip_code_prefix", "customer_state"]].nunique() > 1).any(axis=1).sum()),
              c["customer_unique_id"].nunique(), "person moved / dirty key"),
        issue("orders cancelled/unavailable", o["order_status"].isin(["canceled", "unavailable"]).sum(), len(o),
              "GMV scope decision"),
    ]
    md_table([list(x) for x in sus], ["check", "affected", "% of base", "note"])
    emit("Payment types:")
    emit()
    md_table([[k, n(v)] for k, v in p["payment_type"].value_counts().items()], ["payment_type", "rows"])
    emit("Rows per order in payments (distribution of payment_sequential count):")
    emit()
    md_table([[k, n(v)] for k, v in p.groupby("order_id").size().value_counts().sort_index().items()],
             ["payments per order", "orders"])

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(lines))
    print(f"\n[written] {OUT}")


if __name__ == "__main__":
    main()
